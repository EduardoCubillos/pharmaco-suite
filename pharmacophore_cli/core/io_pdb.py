"""
io_pdb.py — Read/write pharmacophore models in PDB format.

Atom name convention:
  A = ACCEPTOR
  D = DONOR
  H = HYDROPHOBIC
  P = POS_IONIZABLE
  N = NEG_IONIZABLE

For consensus models:
  Occupancy column → fraction of models that support the feature (0.33 / 0.67 / 1.00)
  B-factor column  → confidence level (33.3 / 66.7 / 100.0)
"""

from typing import List, Dict, Any

_TYPE_CHAR   = {"ACCEPTOR": "A", "DONOR": "D", "HYDROPHOBIC": "H",
                "POS_IONIZABLE": "P", "NEG_IONIZABLE": "N"}
_TYPE_RESNUM = {"ACCEPTOR": 1,   "DONOR": 2,   "HYDROPHOBIC": 3,
                "POS_IONIZABLE": 4, "NEG_IONIZABLE": 5}


def write_pharmacophore_pdb(
    features: List[Dict[str, Any]],
    filename: str,
    title: str = "Pharmacophore",
    radius: float = None,
    is_consensus: bool = False,
) -> str:
    """
    Write pharmacophoric features to a PDB file.

    For standard models (SBP/LBP/RBP): occupancy=1.00, bfactor=0.0
    For consensus models: occupancy and bfactor encode the confidence weight.

    Returns the path of the written file.
    """
    lines = [
        f"REMARK  {title}",
        f"REMARK  Generated by pharmaco_suite — github.com/ecubillos",
        f"REMARK  Atom codes: A=Acceptor  D=Donor  H=Hydrophobic  P=PosIon  N=NegIon",
    ]
    if radius is not None:
        lines.append(f"REMARK  Clustering radius: {radius} A")
    if is_consensus:
        lines += [
            "REMARK  Occupancy: 0.33=single model  0.67=two models  1.00=triple consensus",
            "REMARK  B-factor : 33.3=single model  66.7=two models  100.0=triple consensus",
        ]

    for idx, feat in enumerate(features, 1):
        x, y, z = feat["coords"]
        char   = _TYPE_CHAR.get(feat["type"], "X")
        resnum = _TYPE_RESNUM.get(feat["type"], 9)

        if is_consensus:
            weight    = feat.get("weight", 1)
            occupancy = round(weight / 3, 2)
            bfactor   = feat.get("bfactor", round(weight / 3 * 100, 1))
        else:
            occupancy = 1.00
            bfactor   = 0.0

        line = (
            f"ATOM  {idx:5d}  {char:<3s} PH4 A{resnum:4d}    "
            f"{x:8.3f}{y:8.3f}{z:8.3f}"
            f"{occupancy:6.2f}{bfactor:6.1f}          {char:>2s}"
        )
        lines.append(line)

        if is_consensus:
            models_str = "+".join(sorted(feat.get("models", {feat.get("source", "?")})))
            rbp_comp   = feat.get("rbp_complement", "—")
            lines.append(
                f"REMARK  [{idx:3d}] {feat['type']:14s} "
                f"rbp_match={rbp_comp:35s} models={models_str}"
            )
        else:
            lines.append(f"REMARK  [{idx:3d}] {feat['type']:14s} {feat.get('label', '')}")

    lines.append("END")

    with open(filename, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    return filename
